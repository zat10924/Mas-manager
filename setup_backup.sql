-- ===== النسخ الاحتياطي التلقائي (شغّله مرة واحدة: Supabase > SQL Editor > Run) =====
create table if not exists public.backup_snapshots (
  id         bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  kind       text not null default 'auto',
  data       jsonb not null
);
alter table public.backup_snapshots enable row level security;  -- من غير سياسات: الوصول من الدوال بس

-- بناء نسخة من كل الجداول (الكتالوج من غير الصور عشان الحجم)
create or replace function public._backup_build() returns jsonb
language plpgsql security definer set search_path = public as $$
declare t text; j jsonb; res jsonb := jsonb_build_object('exported_at', now());
begin
  foreach t in array array['free_production','glaze_orders','glaze_order_lines','glaze_production','glaze_order_increases','glaze_waste',
                           'deco_orders','deco_lines','deco_production','deco_increases','spray_orders','spray_production',
                           'repair_log','workers','order_postponements'] loop
    if to_regclass('public.' || t) is not null then
      execute format('select coalesce(jsonb_agg(to_jsonb(x)), ''[]''::jsonb) from public.%I x', t) into j;
      res := res || jsonb_build_object(t, j);
    end if;
  end loop;
  if to_regclass('public.catalog') is not null then
    select coalesce(jsonb_agg(to_jsonb(x) - 'image'), '[]'::jsonb) into j from public.catalog x;
    res := res || jsonb_build_object('catalog', j);
  end if;
  return res;
end $$;

-- إنشاء نسخة + الاحتفاظ بآخر p_keep نسخة بس
create or replace function public.make_backup(p_kind text default 'auto', p_keep int default 30) returns bigint
language plpgsql security definer set search_path = public as $$
declare nid bigint;
begin
  insert into public.backup_snapshots(kind, data) values (p_kind, public._backup_build()) returning id into nid;
  delete from public.backup_snapshots where id not in (select id from public.backup_snapshots order by created_at desc, id desc limit greatest(p_keep, 1));
  return nid;
end $$;
revoke all on function public.make_backup(text, int) from public;
revoke all on function public._backup_build() from public;

-- دوال للمدير (من الإعدادات)
create or replace function public.backup_now() returns bigint
language plpgsql security definer set search_path = public as $$
begin
  if not exists (select 1 from public.profiles where id = auth.uid() and role = 'admin' and coalesce(active, true)) then
    raise exception 'not allowed';
  end if;
  return public.make_backup('manual', 30);
end $$;

create or replace function public.backup_list() returns table(id bigint, created_at timestamptz, kind text, size_kb int)
language plpgsql security definer set search_path = public as $$
begin
  if not exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin' and coalesce(p.active, true)) then
    raise exception 'not allowed';
  end if;
  return query select s.id, s.created_at, s.kind, (pg_column_size(s.data) / 1024)::int
                 from public.backup_snapshots s order by s.created_at desc, s.id desc limit 30;
end $$;

create or replace function public.backup_get(p_id bigint) returns jsonb
language plpgsql security definer set search_path = public as $$
declare r jsonb;
begin
  if not exists (select 1 from public.profiles where id = auth.uid() and role = 'admin' and coalesce(active, true)) then
    raise exception 'not allowed';
  end if;
  select data into r from public.backup_snapshots where id = p_id;
  return r;
end $$;

revoke all on function public.backup_now() from public;
revoke all on function public.backup_list() from public;
revoke all on function public.backup_get(bigint) from public;
grant execute on function public.backup_now() to authenticated;
grant execute on function public.backup_list() to authenticated;
grant execute on function public.backup_get(bigint) to authenticated;

-- جدولة يومية 12 بعد نص الليل بتوقيت القاهرة تقريبًا (21:00 UTC) — محتاجة إضافة pg_cron
do $$
begin
  create extension if not exists pg_cron;
  if exists (select 1 from cron.job where jobname = 'mas-daily-backup') then perform cron.unschedule('mas-daily-backup'); end if;
  perform cron.schedule('mas-daily-backup', '0 21 * * *', 'select public.make_backup(''auto'', 30)');
exception when others then
  raise notice 'الجدولة التلقائية ما اتفعلتش (%). فعّل pg_cron من Database > Extensions وشغّل الملف تاني.', sqlerrm;
end $$;

