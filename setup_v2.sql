-- المستخدم يغيّر بيانات الاتصال بتاعته هو بس
create or replace function public.set_my_contact(p_phone text, p_whatsapp text)
returns void language plpgsql security definer set search_path = public as $$
declare
  v_p text := nullif(regexp_replace(coalesce(p_phone, ''), '[^0-9+]', '', 'g'), '');
  v_w text := nullif(regexp_replace(coalesce(p_whatsapp, ''), '[^0-9+]', '', 'g'), '');
begin
  if v_p is not null and length(v_p) not between 7 and 16 then raise exception 'invalid phone'; end if;
  if v_w is not null and length(v_w) not between 7 and 16 then raise exception 'invalid whatsapp'; end if;
  update public.profiles set phone = v_p, whatsapp = v_w where id = auth.uid();
end;
$$;
revoke all on function public.set_my_contact(text, text) from public;
grant execute on function public.set_my_contact(text, text) to authenticated;

-- دالة مساعدة: هل المستخدم الحالي ليه صلاحية على القسم ده؟ (الأدمن أو قسمه الأساسي أو أي قسم في sections)
create or replace function public.can_section(p_sec text)
returns boolean language sql stable security definer set search_path = public as $$
  select exists (
    select 1 from public.profiles p
    where p.id = auth.uid() and coalesce(p.active, true) and p.role is not null
      and (p.role = 'admin' or p.section = p_sec or p_sec = any (coalesce(p.sections, '{}'::text[])))
  );
$$;
revoke all on function public.can_section(text) from public;
grant execute on function public.can_section(text) to authenticated;

create or replace function public.can_manage_section(p_sec text)
returns boolean language sql stable security definer set search_path = public as $$
  select exists (
    select 1 from public.profiles p
    where p.id = auth.uid() and coalesce(p.active, true)
      and (p.role = 'admin'
           or (p.role = 'manager' and (p.section = p_sec or p_sec = any (coalesce(p.sections, '{}'::text[])))))
  );
$$;
revoke all on function public.can_manage_section(text) from public;
grant execute on function public.can_manage_section(text) to authenticated;

-- ---------- 2) كود وصورة للصنف ----------
alter table public.catalog add column if not exists code text;
alter table public.catalog add column if not exists image text;

-- تعديل الكود والصورة (للمدير بس). p_set_image = true معناها غيّر الصورة (حتى لو null = حذف الصورة)
create or replace function public.catalog_set_meta(p_id bigint, p_code text, p_image text, p_set_image boolean default true)
returns void language plpgsql security definer set search_path = public as $$
begin
  if not exists (select 1 from public.profiles where id = auth.uid() and role = 'admin' and coalesce(active, true)) then
    raise exception 'not allowed';
  end if;
  if p_image is not null and (length(p_image) > 400000 or p_image !~ '^data:image/(jpeg|png|webp);base64,[A-Za-z0-9+/=]+$') then
    raise exception 'invalid image';
  end if;
  update public.catalog
     set code = nullif(trim(p_code), ''),
         image = case when p_set_image then p_image else image end
   where id = p_id;
end;
$$;
revoke all on function public.catalog_set_meta(bigint, text, text, boolean) from public;
grant execute on function public.catalog_set_meta(bigint, text, text, boolean) to authenticated;

-- ---------- 1) إنتاج بدون طلبية ----------
create table if not exists public.free_production (
  id          bigint generated by default as identity primary key,
  section     text not null check (section in ('glaze', 'deco', 'spray')),
  item        text not null,
  sub         text,                       -- اللون (جليز/رش) أو كود الرسمة (زخرفة)
  qty         integer not null check (qty > 0),
  prod_date   date not null default current_date,
  worker      text,
  note        text,
  client_id   uuid unique,
  created_by  uuid default auth.uid(),
  created_at  timestamptz not null default now()
);
create index if not exists free_production_date_idx on public.free_production (prod_date);
alter table public.free_production enable row level security;

drop policy if exists free_prod_select on public.free_production;
drop policy if exists free_prod_insert on public.free_production;
drop policy if exists free_prod_update on public.free_production;
drop policy if exists free_prod_delete on public.free_production;
create policy free_prod_select on public.free_production for select to authenticated using (public.can_section(section));
create policy free_prod_insert on public.free_production for insert to authenticated with check (public.can_section(section));
create policy free_prod_update on public.free_production for update to authenticated using (public.can_manage_section(section)) with check (public.can_manage_section(section));
create policy free_prod_delete on public.free_production for delete to authenticated using (public.can_manage_section(section));
grant select, insert, update, delete on public.free_production to authenticated;

-- ربط الجدول بسجل النشاط (لو عندك سجل نشاط شغّال بنفس دالة باقي الجداول)
do $$
declare f text;
begin
  select p.oid::regproc::text into f
  from pg_trigger t join pg_proc p on p.oid = t.tgfoid
  where t.tgrelid = 'public.glaze_production'::regclass and not t.tgisinternal
    and p.proname ilike '%log%' and p.pronargs = 0
  limit 1;
  if f is not null then
    execute 'drop trigger if exists trg_activity_free_production on public.free_production';
    execute format('create trigger trg_activity_free_production after insert or update or delete on public.free_production for each row execute function %s()', f);
  end if;
exception when others then
  raise notice 'تخطّيت ربط سجل النشاط: %', sqlerrm;
end $$;

-- ---------- 5) حماية حسابات المديرين ----------
-- لما auth.uid() بيبقى null (يعني التعديل جاي من Supabase SQL Editor / Table Editor / service role)
-- الحماية بتتخطّى — وده المسموح الوحيد لتعديل مدير.
create or replace function public.protect_admin_profiles()
returns trigger language plpgsql security definer set search_path = public as $$
declare v_me uuid := auth.uid();
begin
  if v_me is null then
    return case when tg_op = 'DELETE' then old else new end;
  end if;
  if tg_op = 'DELETE' then
    if old.role = 'admin' then raise exception 'protected admin'; end if;
    return old;
  elsif tg_op = 'INSERT' then
    if new.role = 'admin' then raise exception 'protected admin'; end if;
    return new;
  else
    -- مدير تاني: ممنوع أي تعديل
    if old.role = 'admin' and old.id <> v_me then raise exception 'protected admin'; end if;
    -- ممنوع ترقية حد لمدير من البرنامج
    if new.role = 'admin' and old.role is distinct from 'admin' then raise exception 'protected admin'; end if;
    -- المدير ما يقدرش يغيّر دوره أو يوقف نفسه
    if old.id = v_me and old.role = 'admin'
       and (new.role is distinct from old.role or coalesce(new.active, true) is distinct from coalesce(old.active, true)) then
      raise exception 'protected admin';
    end if;
    return new;
  end if;
end;
$$;
drop trigger if exists trg_protect_admin_profiles on public.profiles;
create trigger trg_protect_admin_profiles
  before insert or update or delete on public.profiles
  for each row execute function public.protect_admin_profiles();

-- حذف مستخدم: ممنوع لو المستهدف مدير
create or replace function public.delete_user(p_id uuid)
returns void language plpgsql security definer set search_path = public, auth as $$
begin
  if not exists (select 1 from public.profiles where id = auth.uid() and role = 'admin' and coalesce(active, true)) then
    raise exception 'not allowed';
  end if;
  if p_id = auth.uid() then raise exception 'cannot delete yourself'; end if;
  if exists (select 1 from public.profiles where id = p_id and role = 'admin') then
    raise exception 'protected admin';
  end if;
  delete from public.profiles where id = p_id;
  delete from auth.users where id = p_id;
end;
$$;
revoke all on function public.delete_user(uuid) from public;
grant execute on function public.delete_user(uuid) to authenticated;

-- تغيير كلمة سر: المدير يقدر يغيّر لغير المديرين بس
create or replace function public.admin_set_password(p_id uuid, p_password text)
returns void language plpgsql security definer set search_path = public, auth, extensions as $$
begin
  if not exists (select 1 from public.profiles where id = auth.uid() and role = 'admin' and coalesce(active, true)) then
    raise exception 'not allowed';
  end if;
  if length(coalesce(p_password, '')) < 6 then raise exception 'password too short'; end if;
  if exists (select 1 from public.profiles where id = p_id and role = 'admin') then
    raise exception 'protected admin';
  end if;
  update auth.users set encrypted_password = extensions.crypt(p_password, extensions.gen_salt('bf')), updated_at = now()
  where id = p_id;
end;
$$;
revoke all on function public.admin_set_password(uuid, text) from public;
grant execute on function public.admin_set_password(uuid, text) to authenticated;

-- إنشاء مستخدم بالاسم: ممنوع إنشاء مدير من البرنامج
create or replace function public.admin_create_user(
  p_name text, p_password text, p_role text, p_section text, p_perms jsonb default '{}'::jsonb)
returns uuid language plpgsql security definer set search_path = public, auth, extensions as $$
declare
  v_id uuid := gen_random_uuid();
  v_email text;
  v_name text := regexp_replace(trim(p_name), '\s+', ' ', 'g');
begin
  if not exists (select 1 from public.profiles where id = auth.uid() and role = 'admin' and coalesce(active, true)) then
    raise exception 'not allowed';
  end if;
  if length(v_name) < 2 then raise exception 'name too short'; end if;
  if length(coalesce(p_password, '')) < 6 then raise exception 'password too short'; end if;
  if p_role not in ('manager', 'worker') then raise exception 'bad role'; end if;
  if exists (select 1 from public.profiles
             where lower(regexp_replace(trim(full_name), '\s+', ' ', 'g')) = lower(v_name)) then
    raise exception 'name already exists';
  end if;

  v_email := 'u' || substr(replace(v_id::text, '-', ''), 1, 14) || '@noemail.mas.app';

  insert into auth.users (
    instance_id, id, aud, role, email, encrypted_password, email_confirmed_at,
    raw_app_meta_data, raw_user_meta_data, created_at, updated_at,
    confirmation_token, recovery_token, email_change, email_change_token_new)
  values (
    '00000000-0000-0000-0000-000000000000', v_id, 'authenticated', 'authenticated', v_email,
    extensions.crypt(p_password, extensions.gen_salt('bf')), now(),
    '{"provider":"email","providers":["email"]}'::jsonb, jsonb_build_object('full_name', v_name),
    now(), now(), '', '', '', '');

  insert into auth.identities (id, user_id, provider_id, identity_data, provider, last_sign_in_at, created_at, updated_at)
  values (gen_random_uuid(), v_id, v_id::text,
          jsonb_build_object('sub', v_id::text, 'email', v_email, 'email_verified', true),
          'email', now(), now(), now());

  insert into public.profiles (id, full_name, email, role, section, sections, active, perms)
  values (v_id, v_name, v_email, p_role, p_section,
          case when p_section is null then null else array[p_section] end, true, coalesce(p_perms, '{}'::jsonb))
  on conflict (id) do update set
    full_name = excluded.full_name, email = excluded.email, role = excluded.role,
    section = excluded.section, sections = excluded.sections, active = true, perms = excluded.perms;

  return v_id;
end;
$$;
revoke all on function public.admin_create_user(text, text, text, text, jsonb) from public;
grant execute on function public.admin_create_user(text, text, text, text, jsonb) to authenticated;

